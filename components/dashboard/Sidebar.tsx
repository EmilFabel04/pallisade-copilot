export function Sidebar() {
  const pathname = usePathname();
  const { isCollapsed, toggleSidebar } = useSidebar();

  const isActive = (href: string) => {
    if (href === '/dashboard') {
      return pathname === '/dashboard';
    }
    return pathname.startsWith(href);
  };

  return (
    <aside 
      className={`
        fixed left-0 top-0 h-screen z-40
        bg-[var(--surface-inset)] border-r border-[var(--border-faint)]
        flex flex-col
        transition-all duration-300 ease-in-out
        ${isCollapsed ? 'w-[68px]' : 'w-[240px]'}
      `}
    >
      {/* Logo */}
      <div className={`h-14 flex items-center border-b border-[var(--border-faint)] ${isCollapsed ? 'justify-center px-3' : 'px-4'}`}>
        <Link href="/dashboard" className="flex items-center gap-2.5 group">
          <div className="w-8 h-8 flex items-center justify-center flex-shrink-0">
            <img 
              src="/pallisade_emblem.svg" 
              alt="Pallisade" 
              className="w-7 h-7"
            />
          </div>
          {!isCollapsed && (
            <span className="font-semibold text-[15px] text-[var(--text)] tracking-tight">
              Pallisade
            </span>
          )}
        </Link>
      </div>

      {/* Main Navigation */}
      <nav className="flex-1 py-3 px-2 overflow-y-auto">
        <div className="space-y-0.5">
          {navigation.map((item) => {
            const active = isActive(item.href);
            return (
              <Link
                key={item.name}
                href={item.href}
                className={`
                  flex items-center gap-3 px-3 py-2 rounded-lg
                  transition-all duration-150
                  ${active 
                    ? 'bg-[var(--hover-bg)] text-[var(--text)]'
                    : 'text-[var(--text-tertiary)] hover:text-[var(--text)] hover:bg-[var(--overlay-bg)]'
                  }
                  ${isCollapsed ? 'justify-center' : ''}
                `}
                title={isCollapsed ? item.name : undefined}
              >
                <span className={`flex-shrink-0 ${active ? 'text-[#ff0000]' : ''}`}>
                  {item.icon}
                </span>
                {!isCollapsed && (
                  <span className="text-[13px] font-medium">{item.name}</span>
                )}
              </Link>
            );
          })}
        </div>

        {/* Divider */}
        <div className="my-4 mx-3 h-px bg-[var(--hover-bg)]" />

        {/* Secondary Navigation */}
        <div className="space-y-0.5">
          {secondaryNav.map((item) => {
            const active = isActive(item.href);
            return (
              <Link
                key={item.name}
                href={item.href}
                className={`
                  flex items-center gap-3 px-3 py-2 rounded-lg
                  transition-all duration-150
                  ${active 
                    ? 'bg-[var(--hover-bg)] text-[var(--text)]'
                    : 'text-[var(--text-tertiary)] hover:text-[var(--text)] hover:bg-[var(--overlay-bg)]'
                  }
                  ${isCollapsed ? 'justify-center' : ''}
                `}
                title={isCollapsed ? item.name : undefined}
              >
                <span className={`flex-shrink-0 ${active ? 'text-[#ff0000]' : ''}`}>
                  {item.icon}
                </span>
                {!isCollapsed && (
                  <span className="text-[13px] font-medium">{item.name}</span>
                )}
              </Link>
            );
          })}
        </div>
      </nav>

      {/* Footer */}
      <div className="p-2 border-t border-[var(--subtle-border)]">
        {/* Collapse Toggle */}
        <button
          onClick={toggleSidebar}
          className={`
            w-full flex items-center gap-3 px-3 py-2 rounded-lg
            text-[var(--muted)] hover:text-[var(--text)] hover:bg-[var(--overlay-bg)]
            transition-all duration-150
            ${isCollapsed ? 'justify-center' : ''}
          `}
          title={isCollapsed ? 'Expand' : 'Collapse'}
        >
          <svg 
            className={`w-5 h-5 flex-shrink-0 transition-transform duration-200 ${isCollapsed ? 'rotate-180' : ''}`} 
            fill="none" 
            stroke="currentColor" 
            viewBox="0 0 24 24"
          >
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M11 19l-7-7 7-7m8 14l-7-7 7-7" />
          </svg>
          {!isCollapsed && <span className="text-[13px]">Collapse</span>}
        </button>
        
        {/* Sign Out */}
        <button
          onClick={() => signOut({ callbackUrl: '/' })}
          className={`
            w-full flex items-center gap-3 px-3 py-2 rounded-lg
            text-[var(--muted)] hover:text-[var(--text)] hover:bg-[var(--overlay-bg)]
            transition-all duration-150
            ${isCollapsed ? 'justify-center' : ''}
          `}
          title={isCollapsed ? 'Sign out' : undefined}
        >
          <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          {!isCollapsed && <span className="text-[13px]">Sign out</span>}
        </button>
      </div>
    </aside>
  );
}
